#include "subgraph.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <inttypes.h>

int generate_induced_subgraph(
    const CSRGraph *full_g,
    uint32_t target_nodes,
    uint32_t seed_node,
    const char *out_path,
    uint32_t *actual_nodes_out,
    uint64_t *actual_arcs_out
) {
    if (!full_g || !out_path || target_nodes == 0) return -1;
    if (seed_node >= full_g->num_nodes) seed_node = 0;
    if (target_nodes > full_g->num_nodes) target_nodes = full_g->num_nodes;

    uint32_t n = full_g->num_nodes;
    uint8_t *visited = (uint8_t *)calloc(n, sizeof(uint8_t));
    uint32_t *selected = (uint32_t *)malloc(target_nodes * sizeof(uint32_t));
    uint32_t *queue = (uint32_t *)malloc(n * sizeof(uint32_t));
    int32_t *old_to_new = (int32_t *)malloc(n * sizeof(int32_t));

    if (!visited || !selected || !queue || !old_to_new) {
        if (visited) free(visited);
        if (selected) free(selected);
        if (queue) free(queue);
        if (old_to_new) free(old_to_new);
        return -2;
    }

    for (uint32_t i = 0; i < n; i++) old_to_new[i] = -1;

    /* Deterministic BFS traversal from seed_node */
    uint32_t head = 0, tail = 0;
    uint32_t count = 0;

    queue[tail++] = seed_node;
    visited[seed_node] = 1;
    selected[count] = seed_node;
    old_to_new[seed_node] = (int32_t)count;
    count++;

    while (head < tail && count < target_nodes) {
        uint32_t u = queue[head++];
        uint64_t start = full_g->row_ptr[u];
        uint64_t end = full_g->row_ptr[u + 1];

        for (uint64_t e = start; e < end; e++) {
            uint32_t v = full_g->col_idx[e];
            if (!visited[v]) {
                visited[v] = 1;
                selected[count] = v;
                old_to_new[v] = (int32_t)count;
                count++;
                queue[tail++] = v;
                if (count >= target_nodes) break;
            }
        }
    }

    /* Fallback fill if BFS component had fewer vertices than target_nodes */
    if (count < target_nodes) {
        for (uint32_t u = 0; u < n && count < target_nodes; u++) {
            if (!visited[u]) {
                visited[u] = 1;
                selected[count] = u;
                old_to_new[u] = (int32_t)count;
                count++;
            }
        }
    }

    /* Pass 1: Count induced arcs */
    uint64_t induced_arcs = 0;
    for (uint32_t i = 0; i < count; i++) {
        uint32_t orig_u = selected[i];
        uint64_t start = full_g->row_ptr[orig_u];
        uint64_t end = full_g->row_ptr[orig_u + 1];

        for (uint64_t e = start; e < end; e++) {
            uint32_t orig_v = full_g->col_idx[e];
            if (old_to_new[orig_v] != -1) {
                induced_arcs++;
            }
        }
    }

    /* Pass 2: Write out valid DIMACS9 file */
    FILE *f = fopen(out_path, "w");
    if (!f) {
        free(visited);
        free(selected);
        free(queue);
        free(old_to_new);
        return -3;
    }

    fprintf(f, "c Deterministic Induced Subgraph of USA-road-d.BAY\n");
    fprintf(f, "c Generated by Intelligent Route Planning Engine via BFS from seed %" PRIu32 "\n", seed_node + 1);
    fprintf(f, "p sp %" PRIu32 " %" PRIu64 "\n", count, induced_arcs);

    for (uint32_t i = 0; i < count; i++) {
        uint32_t orig_u = selected[i];
        int32_t new_u = old_to_new[orig_u] + 1; /* 1-indexed */
        uint64_t start = full_g->row_ptr[orig_u];
        uint64_t end = full_g->row_ptr[orig_u + 1];

        for (uint64_t e = start; e < end; e++) {
            uint32_t orig_v = full_g->col_idx[e];
            int32_t new_v = old_to_new[orig_v];
            if (new_v != -1) {
                new_v += 1; /* 1-indexed */
                uint32_t w = full_g->weights[e];
                fprintf(f, "a %" PRId32 " %" PRId32 " %" PRIu32 "\n", new_u, new_v, w);
            }
        }
    }

    fclose(f);

    if (actual_nodes_out) *actual_nodes_out = count;
    if (actual_arcs_out) *actual_arcs_out = induced_arcs;

    free(visited);
    free(selected);
    free(queue);
    free(old_to_new);
    return 0;
}
